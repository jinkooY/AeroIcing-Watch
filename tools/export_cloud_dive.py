"""Export Cloud Dive cases (manifest-driven).

    python tools/export_cloud_dive.py --manifest tools/cloud_dive_cases/20261112-kjfk-kbna-1930z.json
    python tools/export_cloud_dive.py --all [--out static/cloud-dive/cases]
    python tools/export_cloud_dive.py --all --simulated          # no network: labelled "Simulated"
    python tools/export_cloud_dive.py --all --draft              # write failing cases to data/cloud-dive-draft

Real cases read GOES CONUS scans (cached under data/goes_conus) and an ECMWF IFS bundle chosen by
run time from data/ifs (see tools/collect_ifs.py). A case is written to the output folder only when
it passes the balance criteria B1 to B3 (B4 is checked across cases by tools/tune_params.py); with
--draft it is written to a draft folder instead so the tuner can look at it.

The output never contains absolute paths or secrets and never contains NaN or infinity.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.analysis import case_builder as cb  # noqa: E402
from src.analysis.cost_model import Params, default_params  # noqa: E402
from src.analysis.ifs_cube import build_cube  # noqa: E402
from src.analysis.lanes import build_lanes  # noqa: E402
from src.analysis.solver import balance, solve_references  # noqa: E402

MANIFESTS = ROOT / "tools" / "cloud_dive_cases"
DEFAULT_OUT = ROOT / "static" / "cloud-dive" / "cases"
DRAFT_OUT = ROOT / "data" / "cloud-dive-draft"
AIRPORTS = ROOT / "airports.json"
ATTRIBUTION = [
    "Satellite data: NOAA GOES-R series ABI Level-2 products (public domain), NOAA Open Data Dissemination on AWS.",
    "Forecast data: ECMWF Open Data, IFS 0.25 degree, licence CC BY 4.0.",
    "Fuel tables: derived offline with OpenAP (LGPL-3.0) for the E75L; OpenAP itself is not distributed.",
    "Cloud base: Noh et al. (2017) statistical estimate, not an observation.",
]


def apply_overrides(params: Params, overrides) -> Params:
    if not overrides:
        return params
    d = params.to_dict()
    unknown = [k for k in overrides if k not in d or isinstance(d[k], (dict, str))]
    if unknown:
        raise ValueError(f"unknown parameter overrides: {unknown}")
    d.update({k: float(v) for k, v in overrides.items()})
    return Params.from_dict(d)


def find_bundle(root: Path, run):
    """Newest IFS bundle of the given run (by run time, not by receipt time)."""
    from src.integration.ifs_grid import bundles

    candidates = [(received, bundle) for initialized, received, bundle in bundles(root)
                  if initialized == run and bundle[0]["product"] == "0p25"]
    if not candidates:
        raise SystemExit(f"no IFS bundle for run {run:%Y-%m-%d %H}Z in {root}; run tools/collect_ifs.py first")
    return max(candidates, key=lambda c: c[0])[1]


def real_inputs(m: cb.Manifest, lanes, ifs_root: Path):
    from src.analysis.goes_lane_sampler import provenance, sample_lanes
    from src.integration.goes_conus import get_scene

    scene = get_scene(m.satellite, m.observed_utc)
    sat = sample_lanes(scene, lanes)
    bundle = find_bundle(ifs_root, m.forecast_run)
    cube = build_cube(bundle, lanes, m.alts_ft, m.observed_utc)
    meta = bundle[0]
    sources = {
        "satellite": {**provenance(scene), "layers": {"phase": "ACTPC 2 km", "height": "ACHAC 10 km",
                                                      "opticalDepth": "CODC 2 km", "particleSize": "CPSC 2 km"}},
        "forecast": {"name": "ECMWF IFS open data 0p25", "runUtc": meta["initialized_at"], "receivedUtc": meta["received_at"],
                     "validTimesUtc": meta["valid_times"], "pressureLevelsHpa": meta["pressure_levels_hpa"],
                     "timeInterpolation": "linear between the two bundle times", "mirror": meta.get("mirror")},
        "forecastUnavailableCells": dict(cube.reasons),
        "attribution": ATTRIBUTION,
    }
    return sat, cube, sources


def build_one(m: cb.Manifest, airports, ifs_root: Path):
    a, b = airports[m.origin], airports[m.destination]
    lanes = build_lanes(a["lat"], a["lon"], b["lat"], b["lon"], step_km=m.step_km, lanes_km=m.lanes_km)
    if m.simulated:
        sat, cube = cb.simulated_inputs(m, lanes)
        sources = {"satellite": {"name": "Simulated test world", "note": "No real data."},
                   "forecast": {"name": "Simulated test world"}, "attribution": ["Simulated data generated by this project."]}
    else:
        sat, cube, sources = real_inputs(m, lanes, ifs_root)
    grid = cb.evaluate_grid(sat, cube.forecast, cube.headwind_kt, cube.isotherms, m.alts_ft)
    params = apply_overrides(default_params(m.alts_ft), m.param_overrides)
    case = cb.make_game_case(m, lanes, grid, params)
    refs = solve_references(case)
    flags = balance(refs, case.params)
    case_file = cb.assemble_case_file(m, lanes, case, grid, sat, cube, refs, flags, sources, airports)
    return case_file, refs, flags


def write_index(out: Path) -> None:
    entries = []
    for p in sorted(out.glob("*.json")):
        if p.name == "index.json":
            continue
        d = json.loads(p.read_text(encoding="utf-8"))
        entries.append({
            "id": d["id"], "title": d["title"], "dataKind": d["dataKind"], "file": p.name,
            "observedAtUtc": d["observedAtUtc"], "route": {k: d["route"][k] for k in ("from", "to", "lengthKm")},
            "balance": d["balance"],
        })
    (out / "index.json").write_text(json.dumps({"schemaVersion": 2, "cases": entries}, indent=1) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, action="append", default=[])
    ap.add_argument("--all", action="store_true", help="every manifest in tools/cloud_dive_cases")
    ap.add_argument("--out", type=Path)
    ap.add_argument("--simulated", action="store_true", help="replace the data with the labelled synthetic world")
    ap.add_argument("--draft", action="store_true", help="write cases that fail the balance criteria to a draft folder")
    ap.add_argument("--ifs-root", type=Path, default=ROOT / "data" / "ifs")
    args = ap.parse_args()
    files = sorted(MANIFESTS.glob("*.json")) if args.all else args.manifest
    if not files:
        ap.error("give --manifest or --all")
    airports = json.loads(AIRPORTS.read_text(encoding="utf-8"))
    out = args.out or (DRAFT_OUT if args.draft else DEFAULT_OUT)
    status = 0
    for path in files:
        raw = json.loads(path.read_text(encoding="utf-8"))
        if args.simulated:
            raw = {**raw, "satellite": "simulated", "id": "simulated-" + raw["id"], "forecastRun": None}
        m = cb.load_manifest(raw)
        case_file, refs, flags = build_one(m, airports, args.ifs_root)
        reasons = cb.refusal_reasons(flags, refs)
        text = cb.dumps_strict(case_file)
        best, ahead = refs["best"].cost_usd, refs["straight_ahead"].cost_usd
        print(f"{m.id}: best ${best:.0f}, straight-ahead ${ahead:.0f}, balance {flags}"
              + (f"  REFUSED: {', '.join(reasons)}" if reasons else ""))
        if reasons and not args.draft:
            status = 1
            continue
        out.mkdir(parents=True, exist_ok=True)
        (out / f"{m.id}.json").write_text(text + "\n", encoding="utf-8")
        write_index(out)
        print(f"  wrote {out.name}/{m.id}.json ({len(text) // 1024} KB)")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
